function isPreventedNavOrRedirect(url: URL): boolean {
  return (
    url.hostname !== "consent.youtube.com" &&
    url.hostname !== "accounts.youtube.com" &&
    url.hostname !== "music.youtube.com" &&
    !(
      (url.hostname === "www.youtube.com" || url.hostname === "youtube.com") &&
      (url.pathname === "/signin" || url.pathname === "/premium" || url.pathname === "/musicpremium" || url.pathname === "/signin_prompt")
    ) &&
    !urlIsGoogleAccountsDomain(url)
  );
}

const createYTMView = (): void => {
  memoryStore.set("ytmViewLoadTimedout", false);
  memoryStore.set("ytmViewLoading", true);
  memoryStore.set("ytmViewLoadingStatus", "Initializing...");

  ytmView = new BrowserView({
    webPreferences: {
      sandbox: true,
      contextIsolation: true,
      partition: app.isPackaged ? "persist:ytmview" : "persist:ytmview-dev",
      preload: path.join(__dirname, `../renderer/windows/ytmview/preload.js`),
      autoplayPolicy: store.get("playback.continueWhereYouLeftOffPaused") ? "document-user-activation-required" : "no-user-gesture-required"
    }
  });
  // #region agent log (debug instrumentation)
  __ytmdDbg("S2", "main/index.ts:createYTMView", "ytmView created", {
    continueWhereYouLeftOff: Boolean(store.get("playback.continueWhereYouLeftOff")),
    continueWhereYouLeftOffPaused: Boolean(store.get("playback.continueWhereYouLeftOffPaused")),
    autoplayPolicy: store.get("playback.continueWhereYouLeftOffPaused") ? "document-user-activation-required" : "no-user-gesture-required",
    storedLastUrl: String(store.get("state.lastUrl") || ""),
    storedLastVideoId: String(store.get("state.lastVideoId") || ""),
    storedLastPlaylistId: String(store.get("state.lastPlaylistId") || "")
  });
  // #endregion agent log (debug instrumentation)
  companionServer.provide(store, memoryStore, ytmView);
  customCss.provide(store, ytmView);
  ratioVolume.provide(ytmView);

  // Attach events to ytm view
  ytmView.webContents.on("will-navigate", event => {
    const url = new URL(event.url);
    if (isPreventedNavOrRedirect(url)) {
      event.preventDefault();
      log.info(`Blocking YTM View navigation to ${event.url}`);

      openExternalFromYtmView(event.url);
    }
  });

  // Set Content Security Policy to reduce unsafe-eval warnings
  ytmView.webContents.session.webRequest.onHeadersReceived((details, callback) => {
    if (details.url.startsWith("https://music.youtube.com/")) {
      const responseHeaders = details.responseHeaders || {};
      const existingCSP = responseHeaders["content-security-policy"] || [];

      // Modify the CSP to allow safer inline script execution with nonce
      const cspModification = existingCSP.map(policy => {
        // Add 'strict-dynamic' to script-src to allow better dynamic script loading patterns
        // Replace 'unsafe-eval' with safer alternatives where possible
        return policy
          .replace(/script-src([^;]*);/g, "script-src$1 'strict-dynamic' https: http:;")
          .replace(/style-src([^;]*);/g, "style-src$1 'unsafe-inline' https: http:;");
      });

      if (cspModification.length > 0) {
        responseHeaders["content-security-policy"] = cspModification;
      }

      callback({ responseHeaders });
    } else {
      callback({ responseHeaders: details.responseHeaders });
    }
  });

  // Handle CORS errors from YouTube ad services
  ytmView.webContents.session.webRequest.onHeadersReceived(
    { urls: ["https://www.youtube.com/pagead/*", "https://*.doubleclick.net/*"] },
    (details, callback) => {
      if (details.resourceType === "xhr") {
        const responseHeaders = details.responseHeaders || {};

        // Fix CORS by setting proper Access-Control-Allow-Origin header
        responseHeaders["access-control-allow-origin"] = ["https://music.youtube.com"];
        responseHeaders["access-control-allow-credentials"] = ["true"];

        callback({ responseHeaders });
      } else {
        callback({ responseHeaders: details.responseHeaders });
      }
    }
  );

  ytmView.webContents.on("will-redirect", event => {
    const url = new URL(event.url);
    if (isPreventedNavOrRedirect(url)) {
      event.preventDefault();
      log.info(`Blocking YTM View redirect to ${event.url}`);
    }

    if (
      (url.hostname === "www.youtube.com" && url.pathname === "/premium") ||
      (url.hostname === "youtube.com" && url.pathname === "/premium") ||
      (url.hostname === "www.youtube.com" && url.pathname === "/musicpremium") ||
      (url.hostname === "youtube.com" && url.pathname === "/musicpremium")
    ) {
      // This users region requires a premium subscription to use YTM
      ytmView.webContents.loadURL(
        "https://accounts.google.com/ServiceLogin?ltmpl=music&service=youtube&continue=https%3A%2F%2Fwww.youtube.com%2Fsignin%3Faction_handle_signin%3Dtrue%26app%3Ddesktop%26next%3Dhttps%253A%252F%252Fmusic.youtube.com%252F"
      );
    }
  });
  ytmView.webContents.on("did-navigate", ytmViewNavigated);
  ytmView.webContents.on("did-navigate-in-page", ytmViewNavigated);
  ytmView.webContents.on("enter-html-full-screen", () => {
    if (mainWindow) {
      mainWindow.setFullScreen(true);
    }
  });
  ytmView.webContents.on("leave-html-full-screen", () => {
    if (mainWindow) {
      mainWindow.setFullScreen(false);
    }
  });
  ytmView.webContents.on("render-process-gone", () => {
    try {
      // Save state before recreating view
      saveState();
    } catch (error) {
      log.error("Failed to save state after render process crash:", error);
    }
    createYTMView();
  });
  ytmView.webContents.on("page-title-updated", (_event, title) => {
    if (mainWindow) {
      mainWindow.setTitle(`${title} | YouTube Music Desktop App`);
    }
  });
  ytmView.webContents.on("context-menu", (_event, params) => {
    if (store.get("developer.enableDevTools")) {
      Menu.buildFromTemplate([
        {
          label: "YouTube Music Desktop",
          type: "normal",
          enabled: false
        },
        {
          type: "separator"
        },
        {
          label: "Open Developer Tools",
          type: "normal",
          click: () => {
            if (ytmView) {
              ytmView.webContents.openDevTools({
                mode: "detach"
              });
            }
          }
        }
      ]).popup({
        window: mainWindow,
        x: params.x,
        y: params.y,
        sourceType: params.menuSourceType
      });
    }
  });
  ytmView.webContents.on("will-prevent-unload", event => {
    if (mainWindow) {
      if (!applicationQuitting) {
        if (ytmView.webContents.getURL().startsWith("https://music.youtube.com/")) {
          const choice = dialog.showMessageBoxSync(mainWindow, {
            type: "question",
            buttons: ["Leave", "Stay"],
            title: "Navigation",
            message: "YouTube Music is preventing navigation. Do you want to leave or stay?",
            defaultId: 0,
            cancelId: 1
          });

          if (choice !== 0) {
            return;
          }
        }
      }
    }

    event.preventDefault();
  });
  ytmView.webContents.on("unresponsive", async () => {
    memoryStore.set("ytmViewUnresponsive", true);
    log.warn("YouTube Music view became unresponsive");

    // Start unresponsive timer
    crashReporter.startUnresponsiveTimer(60000); // 60 second timeout

    try {
      await crashReporter.reportUnresponsive(Date.now());
    } catch (error) {
      log.error("Failed to report unresponsive state:", error);
    }
  });
  ytmView.webContents.on("responsive", () => {
    memoryStore.set("ytmViewUnresponsive", false);
    log.info("YouTube Music view became responsive again");

    // Clear unresponsive timer
    crashReporter.clearUnresponsiveTimer();
  });

  ytmView.webContents.setWindowOpenHandler(details => {
    openExternalFromYtmView(details.url);

    return {
      action: "deny"
    };
  });

  // Loading status event handlers
  ytmView.webContents.on("did-start-loading", () => {
    memoryStore.set("ytmViewLoadingStatus", "Loading YouTube Music...");
  });

  ytmView.webContents.on("did-stop-loading", () => {
    if (!memoryStore.get("ytmViewLoadingError")) {
      memoryStore.set("ytmViewLoadingStatus", "Loaded YouTube Music");
    }
  });

  ytmView.webContents.on("did-fail-load", (_event, errorCode, errorDescription, _validatedURL, isMainFrame) => {
    if (isMainFrame) {
      if (ytmViewLoadTimeout) clearTimeout(ytmViewLoadTimeout);

      memoryStore.set("ytmViewLoadingError", true);
      memoryStore.set("ytmViewLoadingStatus", `Failed to load YouTube Music: ${errorDescription} (${errorCode})`);

      // Retry loading after a short delay
      setTimeout(() => {
        log.info("Retrying YouTube Music load after failure");
        memoryStore.set("ytmViewLoadingError", false);
        memoryStore.set("ytmViewLoadingStatus", "Retrying...");
        ytmView.webContents.loadURL("https://music.youtube.com/");
      }, 3000);
    }
  });

  memoryStore.set("ytmViewLoadingStatus", "Initialized");

  let navigateDefault = true;

  const continueWhereYouLeftOff: boolean = store.get("playback.continueWhereYouLeftOff");
  if (continueWhereYouLeftOff) {
    const lastUrl: string = store.get("state.lastUrl");
    if (lastUrl) {
      if (lastUrl.startsWith("https://music.youtube.com/")) {
        // #region agent log (debug instrumentation)
        __ytmdDbg("S3", "main/index.ts:createYTMView", "loading lastUrl", { lastUrl });
        // #endregion agent log (debug instrumentation)
        ytmView.webContents.loadURL(lastUrl);
        navigateDefault = false;
      }
    }
  }

  if (navigateDefault) {
    ytmView.webContents.loadURL("https://music.youtube.com/");
    lastUrl = "https://music.youtube.com/";
    // Don't immediately save to disk, let the normal state saving handle it
  }

  ytmViewLoadTimeout = setTimeout(() => {
    memoryStore.set("ytmViewLoadTimedout", true);
    // Force loading to complete after timeout to prevent infinite loading
    memoryStore.set("ytmViewLoading", false);
    memoryStore.set("ytmViewLoadingStatus", "YouTube Music loaded (timeout fallback)");
    log.warn("YouTube Music loading timed out, forcing completion");

    // Add the view to the main window even if loaded signal wasn't received
    if (mainWindow && ytmView) {
      mainWindow.addBrowserView(ytmView);
      ytmView.setBounds({
        x: 0,
        y: 36,
        width: mainWindow.getContentBounds().width,
        height: mainWindow.getContentBounds().height - 36
      });
    }

    // Unregister from cleanup as it has fired
    if (ytmViewLoadTimeout) {
      globalCleanupRegistry.unregisterTimeout(ytmViewLoadTimeout);
    }
  }, 30 * 1000);

  // Register timeout for cleanup
  globalCleanupRegistry.registerTimeout(ytmViewLoadTimeout);
};

const createMainWindow = (): void => {
  // Create the browser window.
  const scaleFactor = screen.getPrimaryDisplay().scaleFactor;
  const storedBounds = store.get("state").windowBounds;
  const windowBounds = (() => {
    if (!storedBounds) return null;

    // Ensure saved bounds are still on-screen (multi-monitor setups can change).
    const displays = screen.getAllDisplays().map(d => d.workArea);
    const intersects = (a: { x: number; y: number; width: number; height: number }, b: { x: number; y: number; width: number; height: number }) =>
      a.x < b.x + b.width && a.x + a.width > b.x && a.y < b.y + b.height && a.y + a.height > b.y;

    const isOnSomeDisplay = displays.some(d => intersects(storedBounds, d));
    if (isOnSomeDisplay) return storedBounds;

    const primary = screen.getPrimaryDisplay().workArea;
    const safeWidth = Math.min(Math.max(storedBounds.width, 156), primary.width);
    const safeHeight = Math.min(Math.max(storedBounds.height, 180), primary.height);
    const safeX = Math.round(primary.x + (primary.width - safeWidth) / 2);
    const safeY = Math.round(primary.y + (primary.height - safeHeight) / 2);

    return { x: safeX, y: safeY, width: safeWidth, height: safeHeight };
  })();
  mainWindow = new BrowserWindow({
    width: windowBounds?.width ?? 1280 / scaleFactor,
    height: windowBounds?.height ?? 720 / scaleFactor,
    x: windowBounds?.x,
    y: windowBounds?.y,
    minWidth: 156,
    minHeight: 180,
    frame: false,
    show: false,
    icon: getIconPath("ytmd.png"),
    titleBarStyle: "hidden",
    titleBarOverlay: {
      color: "#000000",
      symbolColor: "#BBBBBB",
      height: 36
    },
    webPreferences: {
      sandbox: true,
      contextIsolation: true,
      preload: path.join(__dirname, `../renderer/windows/main/preload.js`),
      devTools: store.get("developer.enableDevTools")
    }
  });
  const windowMaximized = store.get("state").windowMaximized;
  // Even though bounds are set when creating the main window we set the bounds again to fix scaling issues. This is classified as an upstream chromium bug.
  if (windowBounds) {
    mainWindow.setBounds(windowBounds);
  }
  if (windowMaximized) {
    mainWindow.maximize();
  }

  // Attach events to main window
  mainWindow.on("resize", () => {
    setTimeout(() => {
      if (ytmView) {
        if (mainWindow.fullScreen) {
          ytmView.setBounds({
            x: 0,
            y: 0,
            width: mainWindow.getContentBounds().width,
            height: mainWindow.getContentBounds().height
          });
        } else {
          ytmView.setBounds({
            x: 0,
            y: 36,
            width: mainWindow.getContentBounds().width,
            height: mainWindow.getContentBounds().height - 36
          });
        }
      }
    });
  });

  mainWindow.on("enter-full-screen", () => {
    setTimeout(() => {
      if (ytmView) {
        ytmView.setBounds({
          x: 0,
          y: 0,
          width: mainWindow.getContentBounds().width,
          height: mainWindow.getContentBounds().height
        });
      }
    });
    sendMainWindowStateIpc();
  });
  mainWindow.on("leave-full-screen", () => {
    setTimeout(() => {
      ytmView.setBounds({
        x: 0,
        y: 36,
        width: mainWindow.getContentBounds().width,
        height: mainWindow.getContentBounds().height - 36
      });
    });
    sendMainWindowStateIpc();
  });
  mainWindow.on("maximize", sendMainWindowStateIpc);
  mainWindow.on("unmaximize", sendMainWindowStateIpc);
  mainWindow.on("minimize", sendMainWindowStateIpc);
  mainWindow.on("restore", sendMainWindowStateIpc);
  mainWindow.on("close", event => {
    if (!applicationQuitting && (store.get("general").hideToTrayOnClose || isDarwin)) {
      event.preventDefault();
      mainWindow.hide();
    }

    store.set("state.windowBounds", mainWindow.getNormalBounds());
    store.set("state.windowMaximized", mainWindow.isMaximized());
  });

  mainWindow.once("closed", () => {
    mainWindow = null;
  });

  mainWindow.webContents.setWindowOpenHandler(() => {
    return {
      action: "deny"
    };
  });

  mainWindow.webContents.on("will-navigate", event => {
    if (process.env.NODE_ENV === "development") if (event.url.startsWith("http://localhost")) return;

    event.preventDefault();
  });

  // Set Content Security Policy for the main window
  mainWindow.webContents.session.webRequest.onHeadersReceived((details, callback) => {
    if (details.url.startsWith("http://localhost") || details.url.startsWith("file://")) {
      const responseHeaders = details.responseHeaders || {};

      // Set a strict CSP for the main window that complies with Electron security requirements
      const csp =
        process.env.NODE_ENV === "development"
          ? "default-src 'self'; " +
            "script-src 'self' 'unsafe-inline' http://localhost:*; " +
            "style-src 'self' 'unsafe-inline' http://localhost:*; " +
            "img-src 'self' data: blob: http://localhost:* https://*.ytimg.com https://*.youtube.com https://*.googleusercontent.com; " +
            "font-src 'self' data: http://localhost:*; " +
            "connect-src 'self' http://localhost:* ws://localhost:* https://*.sentry.io; " +
            "worker-src 'self' blob:;"
          : "default-src 'self'; " +
            "script-src 'self' 'unsafe-inline'; " +
            "style-src 'self' 'unsafe-inline'; " +
            "img-src 'self' data: blob: https://*.ytimg.com https://*.youtube.com https://*.googleusercontent.com; " +
            "font-src 'self' data:; " +
            "connect-src 'self' https://*.sentry.io; " +
            "worker-src 'self' blob:;";

      responseHeaders["content-security-policy"] = [csp];

      callback({ responseHeaders });
    } else {
      callback({ responseHeaders: details.responseHeaders });
    }
  });

  mainWindow.on("ready-to-show", () => {
    mainWindow.show();
    // Open the DevTools.
    if (process.env.NODE_ENV === "development") {
      mainWindow.webContents.openDevTools({
        mode: "detach"
      });
    }
  });

  // and load the index.html of the app.
  if (ALL_WINDOWS_VITE_DEV_SERVER_URL) mainWindow.loadURL(ALL_WINDOWS_VITE_DEV_SERVER_URL + "/windows/main/index.html");
  else mainWindow.loadFile(path.join(__dirname, `../renderer/windows/main/index.html`));
};

