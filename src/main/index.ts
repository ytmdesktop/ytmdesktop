// Throttle function to limit how often a function can be called
function throttle<T>(func: (state: T) => void, limit: number): (state: T) => void {
  let inThrottle = false;
  let lastState: T | null = null;

  return function (state: T) {
    lastState = state;

    if (!inThrottle) {
      func(state);
      inThrottle = true;
      setTimeout(() => {
        inThrottle = false;
        // Check if state changed while throttling
        if (lastState) {
          func(lastState);
        }
      }, limit);
    }
  };
}

// Simple throttle function for functions with no parameters
function simpleThrottle(func: () => void, limit: number): () => void {
  let inThrottle = false;

  return function () {
    if (!inThrottle) {
      func();
      inThrottle = true;
      setTimeout(() => {
        inThrottle = false;
      }, limit);
    }
  };
}

